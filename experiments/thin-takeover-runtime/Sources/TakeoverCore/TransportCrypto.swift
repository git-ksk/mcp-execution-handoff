import CryptoKit
import Foundation

public enum TransportDirection: UInt8, Sendable, Codable {
    case hostToClient = 1
    case clientToHost = 2
}

public enum TransportChannel: UInt8, Sendable, Codable {
    case video = 1
    case inputRealtime = 2
    case inputCritical = 3
    case control = 4
}

public struct TransportCryptoContext: Sendable, Equatable {
    public let sessionHash: UInt64
    public let epoch: UInt64
    public let generation: UInt32
    public let direction: TransportDirection
    public let channel: TransportChannel

    public init(
        sessionHash: UInt64,
        epoch: UInt64,
        generation: UInt32,
        direction: TransportDirection,
        channel: TransportChannel
    ) {
        self.sessionHash = sessionHash
        self.epoch = epoch
        self.generation = generation
        self.direction = direction
        self.channel = channel
    }
}

public enum TransportCryptoError: Error, Equatable {
    case invalidRootKeyLength
    case invalidSealedPayload
    case authenticationFailed
}

/// Frame/message-level AEAD for the thin transport.
///
/// The handoff/control plane owns key establishment. The runtime receives a short-lived
/// 32-byte root key and derives a distinct ChaCha20-Poly1305 key for each
/// session/epoch/generation/direction/channel tuple.
///
/// Every sealed message carries a fresh random 96-bit nonce generated by CryptoKit. Sequence is
/// authenticated as context/replay metadata, but is deliberately not the nonce. This prevents a
/// process restart or accidental sequence reset from reusing a ChaCha20-Poly1305 nonce under an
/// otherwise identical control-plane binding.
public struct TransportCipher: Sendable {
    public static let rootKeyBytes = 32
    public static let nonceBytes = 12
    public static let tagBytes = 16

    private let rootKeyData: Data

    public init(rootKey: Data) throws {
        guard rootKey.count == Self.rootKeyBytes else {
            throw TransportCryptoError.invalidRootKeyLength
        }
        self.rootKeyData = rootKey
    }

    public func seal(
        _ plaintext: Data,
        sequence: UInt64,
        context: TransportCryptoContext,
        associatedData: Data = Data()
    ) throws -> Data {
        let key = derivedKey(for: context)
        let aad = contextAAD(context: context, sequence: sequence, associatedData: associatedData)
        let box = try ChaChaPoly.seal(plaintext, using: key, authenticating: aad)
        var output = Data()
        output.reserveCapacity(Self.nonceBytes + box.ciphertext.count + box.tag.count)
        box.nonce.withUnsafeBytes { output.append(contentsOf: $0) }
        output.append(box.ciphertext)
        output.append(box.tag)
        return output
    }

    public func open(
        _ sealedPayload: Data,
        sequence: UInt64,
        context: TransportCryptoContext,
        associatedData: Data = Data()
    ) throws -> Data {
        let minimumBytes = Self.nonceBytes + Self.tagBytes
        guard sealedPayload.count >= minimumBytes else {
            throw TransportCryptoError.invalidSealedPayload
        }

        let nonceBytes = sealedPayload.prefix(Self.nonceBytes)
        let authenticatedPayload = sealedPayload.dropFirst(Self.nonceBytes)
        let split = authenticatedPayload.count - Self.tagBytes
        let ciphertext = authenticatedPayload.prefix(split)
        let tag = authenticatedPayload.suffix(Self.tagBytes)
        let key = derivedKey(for: context)
        let aad = contextAAD(context: context, sequence: sequence, associatedData: associatedData)

        do {
            let nonce = try ChaChaPoly.Nonce(data: nonceBytes)
            let box = try ChaChaPoly.SealedBox(
                nonce: nonce,
                ciphertext: Data(ciphertext),
                tag: Data(tag)
            )
            return try ChaChaPoly.open(box, using: key, authenticating: aad)
        } catch {
            throw TransportCryptoError.authenticationFailed
        }
    }

    private func derivedKey(for context: TransportCryptoContext) -> SymmetricKey {
        let root = SymmetricKey(data: rootKeyData)
        let info = contextKeyInfo(context)
        return HKDF<SHA256>.deriveKey(
            inputKeyMaterial: root,
            salt: Data("thin-takeover-runtime/v1".utf8),
            info: info,
            outputByteCount: Self.rootKeyBytes
        )
    }

    private func contextKeyInfo(_ context: TransportCryptoContext) -> Data {
        var data = Data("TTKR-key-v1".utf8)
        data.appendInteger(context.sessionHash)
        data.appendInteger(context.epoch)
        data.appendInteger(context.generation)
        data.append(context.direction.rawValue)
        data.append(context.channel.rawValue)
        return data
    }

    private func contextAAD(
        context: TransportCryptoContext,
        sequence: UInt64,
        associatedData: Data
    ) -> Data {
        var data = Data("TTKR-aad-v1".utf8)
        data.appendInteger(context.sessionHash)
        data.appendInteger(context.epoch)
        data.appendInteger(context.generation)
        data.append(context.direction.rawValue)
        data.append(context.channel.rawValue)
        data.appendInteger(sequence)
        data.append(associatedData)
        return data
    }
}

/// Per-datagram authentication for the clear routing header.
///
/// Frame-level AEAD protects encoded bytes after reassembly, but an unauthenticated frame ID or
/// packet count could otherwise evict receiver state before that AEAD check happens. A dedicated
/// 128-bit truncated HMAC authenticates the fixed routing header before the receiver allocates or
/// mutates reassembly state. Payload corruption is still detected by the complete-frame AEAD.
public struct VideoHeaderAuthenticator: Sendable {
    private let key: SymmetricKey

    public init(rootKey: Data, sessionHash: UInt64, epoch: UInt64, generation: UInt32) throws {
        guard rootKey.count == TransportCipher.rootKeyBytes else {
            throw TransportCryptoError.invalidRootKeyLength
        }
        let root = SymmetricKey(data: rootKey)
        var info = Data("TTKR-video-header-auth-v1".utf8)
        info.appendInteger(sessionHash)
        info.appendInteger(epoch)
        info.appendInteger(generation)
        self.key = HKDF<SHA256>.deriveKey(
            inputKeyMaterial: root,
            salt: Data("thin-takeover-runtime/v1".utf8),
            info: info,
            outputByteCount: 32
        )
    }

    public func authenticate(_ header: VideoPacketHeader) -> VideoPacketHeader {
        let mac = HMAC<SHA256>.authenticationCode(for: header.authenticationData(), using: key)
        let bytes = Array(mac.prefix(16))
        var high: UInt64 = 0
        var low: UInt64 = 0
        for byte in bytes.prefix(8) { high = (high << 8) | UInt64(byte) }
        for byte in bytes.dropFirst(8).prefix(8) { low = (low << 8) | UInt64(byte) }
        return header.withAuthenticationTag(high: high, low: low)
    }

    public func verify(_ header: VideoPacketHeader) -> Bool {
        let expected = authenticate(header.withAuthenticationTag(high: 0, low: 0))
        let difference = (expected.authTagHigh ^ header.authTagHigh) | (expected.authTagLow ^ header.authTagLow)
        return difference == 0
    }
}

private extension Data {
    mutating func appendInteger<T: FixedWidthInteger>(_ value: T) {
        var value = value.bigEndian
        Swift.withUnsafeBytes(of: &value) { append(contentsOf: $0) }
    }
}
